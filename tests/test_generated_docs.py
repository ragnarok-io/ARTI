from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import arti
import pytest


ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "generate_docs.py"
SPEC = importlib.util.spec_from_file_location("generate_docs", SCRIPT)
assert SPEC is not None and SPEC.loader is not None
generate_docs = importlib.util.module_from_spec(SPEC)
sys.modules[SPEC.name] = generate_docs
SPEC.loader.exec_module(generate_docs)


def test_generated_capabilities_docs_reflect_public_capabilities_api() -> None:
    content = generate_docs.generate_capabilities_markdown(phases=16)
    caps = arti.capabilities(phases=16)

    assert "Generated by scripts/generate_docs.py" in content
    for name in caps["profiles"]:
        assert f"`{name}`" in content
    for name in caps["scales"]:
        assert f"`{name}`" in content
    for name in caps["plugins"]:
        assert f"`{name}`" in content


def test_generated_capabilities_doc_file_is_current() -> None:
    expected = generate_docs.generate_capabilities_markdown(phases=16)
    actual = (ROOT / "docs" / "reference" / "capabilities.md").read_text(encoding="utf-8")

    assert actual == expected


def test_cli_docs_generate_and_check(tmp_path: Path, capsys) -> None:
    from arti.cli import main

    output_path = tmp_path / "capabilities.md"

    assert main(["docs", "generate", "--output", str(output_path), "--phases", "12"]) == 0
    generate_output = capsys.readouterr().out
    assert '"action": "generate"' in generate_output
    assert output_path.exists()
    assert "Generated from `arti.capabilities(phases=12)`" in output_path.read_text(encoding="utf-8")

    assert main(["docs", "check", "--output", str(output_path), "--phases", "12"]) == 0
    check_output = capsys.readouterr().out
    assert '"action": "check"' in check_output

    output_path.write_text("stale\n", encoding="utf-8")
    assert main(["docs", "check", "--output", str(output_path), "--phases", "12"]) == 1
    assert "out of date" in capsys.readouterr().err


