def test_cli_gate_accepts_qwen_reuse_and_mainline(tmp_path: Path, monkeypatch) -> None:
    from arti.cli import build_parser, run_quality_gate_report

    output_path = tmp_path / "quality_gate_qwen.json"
    captured = []

    class Result:
        returncode = 0
        stdout = "ok"
        stderr = ""

    def fake_run(command: list[str], *, capture_output: bool, text: bool) -> Result:
        captured.append(command)
        output_path.write_text('{"passed": true, "runs": []}', encoding="utf-8")
        return Result()

    monkeypatch.setattr("arti.cli.subprocess.run", fake_run)

    parser = build_parser()
    mainline_args = parser.parse_args(["gate", "mainline"])
    qwen_args = parser.parse_args(["gate", "qwen", "--reuse-passing-producers", "--fail-fast", "--output", str(output_path)])

    assert mainline_args.gates == ["mainline"]
    payload = run_quality_gate_report(qwen_args)

    assert payload["ok"] is True
    assert captured == [
        [
            sys.executable,
            "scripts/quality_gate.py",
            "qwen",
            "--fail-fast",
            "--reuse-passing-producers",
            "--output",
            str(output_path),
        ]
    ]
